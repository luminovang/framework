     *      ->select(['id', 'name'])
     *      ->where('country', '=', 'NN');
     *
     * do {
     *     $rows = $builder->scan($cursor, 100);
     *     foreach ($rows as $row) {
     *         // process row
     *     }
     * } while ($cursor > 0);
     * ```
     */
    public function scan(?int &$iterator, int $limit = 100): ?array
    {
